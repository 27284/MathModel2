function c = layered_config()
%LAYERED_CONFIG 第一问分层处理统一参数
%
% QC v5
%
% 核心原则：
%
% 1. Trial连续质量权重只使用刺激前数据
% 2. 不使用刺激后ERP幅度/P2P判断Trial质量
% 3. clipping / 越界属于不可恢复错误，直接weight=0
% 4. Q1~Q4通过训练折建立robust分布
% 5. Q1~Q4联合形成质量异常分数，而不是只取最差一项


root = fileparts(mfilename('fullpath'));


%% =========================================================
% 数据文件
% =========================================================

c.data_dir = fileparts(root);

% 新版本单独输出
% 不覆盖旧结果
c.output_dir = fullfile( ...
    root, ...
    'ProccesdData', ...
    'layered_qc_huber' ...
    );

c.files = { ...
    'VisualCogA_Task-1.mat', ...
    'VisualCogA_Task-2.mat', ...
    'VisualCogB_Task-1.mat', ...
    'VisualCogB_Task-2.mat' ...
    };

c.channels = { ...
    'Fz', ...
    'F3', ...
    'F4' ...
    };


%% =========================================================
% EEG滤波
% =========================================================

c.lowpass = 30;

c.filter_order = 4;


%% =========================================================
% Epoch
% =========================================================

% 核心Epoch
% -200 ms ~ +800 ms
c.pre = 0.2;

c.post = 0.8;

% EMD及QC的额外上下文
c.padding = 1.0;


%% =========================================================
% clipping
% =========================================================

c.clip_level = 999.9;

c.clip_guard = 0.5;


%% =========================================================
% Trial QC
% =========================================================

% 有效但质量很差的最低权重
c.min_weight = 0.05;

% 5折时间块
c.folds = 5;


% ---------------------------------------------------------
% Q1~Q4 robust z-score标准化阈值
%
% Q1 = baseline MAD
% Q2 = baseline drift
% Q3 = long prestim jump
% Q4 = long prestim slope
%
% 这里不是简单的硬阈值。
%
% 后面会计算：
%
% normalized_k = z_k / threshold_k
%
% 然后联合：
%
% joint_score =
% sqrt(sum(normalized_k^2))
% ---------------------------------------------------------

c.qc_z_thresholds = [ ...
    3.0, ...
    3.0, ...
    4.0, ...
    3.0 ...
    ];


% ---------------------------------------------------------
% 长刺激前QC时间窗
% ---------------------------------------------------------

% 长刺激前窗口：
% -1.0 ~ 0 s
c.qc_long_pre_start = -1.0;

% slope窗口：
% -1.0 ~ -0.2 s
c.qc_slope_end = -0.2;


%% =========================================================
% 背景PCA + 保护空间投影
% =========================================================

c.background_top_fraction = 0.05;

% 训练响应允许最大改变10%
c.max_training_projection_change = 0.10;


%% =========================================================
% EMD
% =========================================================

c.max_imf = 6;

c.max_sift = 50;

c.band_edges = [ ...
    0, ...
    1, ...
    4, ...
    8, ...
    15, ...
    30, ...
    Inf ...
    ];

c.consistency_min = 0.2;

c.ecg_coherence_max = 0.6;

c.spatial_leak_max = 0.5;

c.min_mode_gain = 0.25;


%% =========================================================
% 低维模型
% =========================================================

c.basis_centers = [ ...
    0.08, ...
    0.17, ...
    0.32, ...
    0.65 ...
    ];

c.basis_widths = [ ...
    0.04, ...
    0.06, ...
    0.10, ...
    0.15 ...
    ];

c.ridge = 0.05;

% 最终条件内QC×Huber估计：不再提前把试次波形乘QC权重。
c.huber_c = 1.345;
c.huber_max_iter = 100;
c.huber_tol = 1e-8;


%% =========================================================
% Bootstrap
% =========================================================

c.bootstrap = 300;

c.block_length = 5;

c.seed = 20260924;


end